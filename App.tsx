
import React, { useState, useCallback, useMemo, useEffect, useRef } from 'react';
import Sidebar from './components/Sidebar';
import ChatInterface from './components/ChatInterface';
import { AgentConfig, AgentStatus, Message, VirtualFile, ArtifactRow } from './types';
import { DEFAULT_SYSTEM_PROMPT } from './constants';
import { ZypherAgentController } from './services/zypherService';
import { Terminal, RotateCcw, Cpu, Activity, ShieldCheck, Zap, LayoutPanelLeft, Table as TableIcon, CheckCircle2, AlertCircle, Target, Sparkles, Binary } from 'lucide-react';

const INITIAL_FILES: VirtualFile[] = [
  { path: 'README.md', content: '# Zypher Enterprise v1.9.5\n100% Deterministic Browser Architecture.', language: 'markdown' },
  { path: 'agent/agent.ts', content: '// Source of Truth\nexport const AGENT_MANIFEST = { terminal_listening: false };', language: 'typescript' },
  { path: 'package.json', content: '{\n  "name": "zypher-agent-core",\n  "version": "1.9.5",\n  "scripts": { "dev": "vite" }\n}', language: 'json' },
  { path: 'infra/db/schema.sql', content: 'CREATE TABLE telemetry_audit (\n  id INTEGER PRIMARY KEY,\n  source TEXT,\n  data TEXT\n);', language: 'sql' }
];

const App: React.FC = () => {
  const [sidebarWidth, setSidebarWidth] = useState(260);
  const [artifactsWidth, setArtifactsWidth] = useState(440);
  const [isResizingLeft, setIsResizingLeft] = useState(false);
  const [isResizingRight, setIsResizingRight] = useState(false);

  const [config, setConfig] = useState<AgentConfig>({
    name: 'ZYPHER-NODE-EPSILON',
    systemPrompt: DEFAULT_SYSTEM_PROMPT,
    model: 'zypher-local-kernel-v1',
    tools: ['FS_LIST_FILES', 'FS_READ_FILE', 'GET_SYSTEM_METRICS', 'DB_QUERY'],
    temperature: 0,
  });

  const [messages, setMessages] = useState<Message[]>([]);
  const [status, setStatus] = useState<AgentStatus>(AgentStatus.IDLE);
  const [input, setInput] = useState('');
  const [currentGoal, setCurrentGoal] = useState<string | null>(null);
  const [isReady, setIsReady] = useState(false);
  const [bootLog, setBootLog] = useState<string[]>([]);
  const [kernelLogs, setKernelLogs] = useState<{msg: string, time: string}[]>([]);
  
  // The Artifact: A structured ledger generated by the agent
  const [ledger, setLedger] = useState<ArtifactRow[]>([]);
  
  const currentSessionRef = useRef(0);
  const [files, setFiles] = useState<VirtualFile[]>(INITIAL_FILES);
  const [selectedFile, setSelectedFile] = useState<VirtualFile | null>(INITIAL_FILES[0]);

  const addKernelLog = (msg: string) => {
    const time = new Date().toLocaleTimeString('en-GB', { hour12: false });
    setKernelLogs(prev => [{msg, time}, ...prev].slice(0, 50));
  };

  const addLedgerRow = useCallback((row: ArtifactRow) => {
    setLedger(prev => [row, ...prev].slice(0, 100));
  }, []);

  useEffect(() => {
    const logs = [
      "INITIALIZING ZYPHER KERNEL v1.9.5...",
      "BOOT SEQUENCE COMPLETE. AGENT STANDBY."
    ];
    let i = 0;
    const interval = setInterval(() => {
      if (i < logs.length) {
        setBootLog(prev => [...prev, logs[i]]);
        addKernelLog(logs[i]);
        i++;
      } else {
        clearInterval(interval);
        setTimeout(() => setIsReady(true), 500);
      }
    }, 150);
    return () => clearInterval(interval);
  }, []);

  const handleMouseMove = useCallback((e: MouseEvent) => {
    if (isResizingLeft) setSidebarWidth(Math.max(200, Math.min(450, e.clientX)));
    if (isResizingRight) setArtifactsWidth(Math.max(350, Math.min(800, window.innerWidth - e.clientX)));
  }, [isResizingLeft, isResizingRight]);

  const handleMouseUp = useCallback(() => {
    setIsResizingLeft(false);
    setIsResizingRight(false);
  }, []);

  useEffect(() => {
    if (isResizingLeft || isResizingRight) {
      window.addEventListener('mousemove', handleMouseMove);
      window.addEventListener('mouseup', handleMouseUp);
    }
    return () => {
      window.removeEventListener('mousemove', handleMouseMove);
      window.removeEventListener('mouseup', handleMouseUp);
    };
  }, [isResizingLeft, isResizingRight, handleMouseMove, handleMouseUp]);

  const controller = useMemo(() => new ZypherAgentController(), []);

  const onSend = useCallback(async (text: string) => {
    if (!text.trim() || status !== AgentStatus.IDLE) return;
    
    setCurrentGoal(text);
    addKernelLog(`DIRECTIVE_INITIATED: ${text.toUpperCase()}`);
    const activeSession = currentSessionRef.current;
    const userMsg: Message = { id: `u-${Date.now()}`, role: 'user', content: text, timestamp: Date.now() };
    const history = [...messages, userMsg];
    
    setMessages(history);
    
    try {
      const results = await controller.runReactiveLoop(
        config.model, 
        history, 
        config.systemPrompt, 
        config.tools, 
        files, 
        setFiles, 
        (s) => {
          if (currentSessionRef.current === activeSession) {
            setStatus(s);
          }
        },
        addLedgerRow
      );
      
      if (currentSessionRef.current === activeSession) {
        setMessages(prev => [...prev, ...results]);
        addKernelLog("GOAL_REACHED: State updated.");
      }
    } catch (err: any) {
      addKernelLog(`KERNEL_PANIC: ${err.message}`);
      if (currentSessionRef.current === activeSession) setStatus(AgentStatus.ERROR);
    }
  }, [messages, config, controller, files, status, addLedgerRow]);

  const handleHardReset = useCallback(() => {
    currentSessionRef.current += 1;
    setMessages([]);
    setLedger([]);
    setCurrentGoal(null);
    setStatus(AgentStatus.IDLE);
    addKernelLog("WORKSPACE_PURGE: State reset.");
  }, []);

  if (!isReady) {
    return (
      <div className="h-screen w-full flex flex-col items-center justify-center bg-slate-950">
        <Zap className="w-12 h-12 text-blue-500 animate-pulse mb-6" />
        <div className="flex flex-col gap-2 max-w-xs w-full px-8">
          {bootLog.map((log, idx) => (
            <p key={idx} className="text-[10px] font-mono text-blue-400/80 uppercase tracking-widest truncate text-center">
              &gt; {log}
            </p>
          ))}
        </div>
      </div>
    );
  }

  return (
    <div className="flex h-screen w-full bg-[#fbfcfd] text-slate-700 font-sans overflow-hidden antialiased">
      {/* SIDEBAR */}
      <div style={{ width: sidebarWidth }} className="shrink-0 h-full border-r border-slate-200">
        <Sidebar config={config} setConfig={setConfig} status={status} onReset={handleHardReset} onCreateCleanNode={handleHardReset} />
      </div>
      <div onMouseDown={() => setIsResizingLeft(true)} className="w-1 hover:bg-blue-400/20 cursor-col-resize z-30" />
      
      {/* CONSOLE */}
      <main className="flex-1 flex flex-col bg-white min-w-0">
        <header className="h-14 border-b border-slate-200 px-6 flex items-center justify-between bg-white shrink-0">
          <div className="flex items-center gap-3">
             <div className="p-2 bg-slate-950 rounded-lg"><Binary className="w-4 h-4 text-blue-400" /></div>
             <span className="text-[10px] font-black text-slate-900 uppercase tracking-widest">Zypher Control Terminal</span>
          </div>
        </header>
        <div className="flex-1 overflow-hidden relative">
          <ChatInterface messages={messages} status={status} onSendMessage={onSend} input={input} setInput={setInput} onHardReset={handleHardReset} />
        </div>
      </main>

      <div onMouseDown={() => setIsResizingRight(true)} className="w-1 hover:bg-blue-400/20 cursor-col-resize z-30" />
      
      {/* ARTIFACT CANVAS (PERSISTENT AGENT OUTPUT) */}
      <aside style={{ width: artifactsWidth }} className="flex flex-col bg-slate-50 min-w-0 shrink-0 h-full border-l border-slate-200 overflow-hidden">
        {/* Status Indicator Bar */}
        <div className={`p-4 flex items-center justify-between border-b transition-colors duration-500 ${status !== AgentStatus.IDLE ? 'bg-blue-600 border-blue-700 shadow-lg shadow-blue-500/20' : 'bg-white border-slate-200'}`}>
          <div className="flex items-center gap-3">
            <div className={`w-3 h-3 rounded-full shadow-sm ${status === AgentStatus.IDLE ? 'bg-slate-300' : 'bg-white animate-pulse'}`} />
            <span className={`text-[11px] font-black uppercase tracking-widest ${status === AgentStatus.IDLE ? 'text-slate-500' : 'text-white'}`}>
              Agent Core: {status}
            </span>
          </div>
          {status !== AgentStatus.IDLE && (
            <div className="flex items-center gap-2 px-2 py-1 rounded bg-white/20 text-white text-[9px] font-black uppercase tracking-tighter">
              <Activity className="w-3 h-3" /> LOOP_ACTIVE
            </div>
          )}
        </div>

        <div className="flex-1 flex flex-col p-4 gap-4 overflow-hidden">
          {/* Current Objective Card */}
          <div className="bg-white border border-slate-200 p-5 rounded-2xl shadow-sm">
            <div className="flex items-center gap-2 mb-3">
              <Target className="w-4 h-4 text-blue-500" />
              <span className="text-[10px] font-black text-slate-400 uppercase tracking-widest">Current Objective</span>
            </div>
            <div className="text-[13px] font-bold text-slate-800 leading-tight">
              {currentGoal || "Waiting for protocol directive..."}
            </div>
            {status !== AgentStatus.IDLE && (
              <div className="mt-4 flex items-center gap-4">
                <div className="flex-1 h-1.5 bg-slate-100 rounded-full overflow-hidden">
                  <div className="h-full bg-blue-500 animate-progress-indeterminate w-1/3" />
                </div>
                <span className="text-[9px] font-black text-blue-600 uppercase">Processing...</span>
              </div>
            )}
          </div>

          {/* THE ARTIFACT: Integrity Ledger Table */}
          <div className="flex-1 bg-white border border-slate-200 rounded-2xl shadow-xl overflow-hidden flex flex-col">
            <div className="px-5 py-4 border-b border-slate-100 flex items-center justify-between bg-slate-50/50">
              <div className="flex items-center gap-2.5">
                <TableIcon className="w-4 h-4 text-blue-500" />
                <span className="text-[10px] font-black text-slate-900 uppercase tracking-[0.2em]">Integrity Ledger Artifact</span>
              </div>
              <div className="flex items-center gap-2">
                 <span className="text-[9px] font-bold text-slate-400 uppercase">Synced: {ledger.length} entries</span>
              </div>
            </div>
            
            <div className="flex-1 overflow-auto custom-scrollbar">
              <table className="w-full text-left border-collapse">
                <thead className="sticky top-0 bg-slate-50 z-10">
                  <tr>
                    <th className="px-5 py-3 text-[9px] font-black uppercase tracking-widest text-slate-400 border-b border-slate-100">Target</th>
                    <th className="px-5 py-3 text-[9px] font-black uppercase tracking-widest text-slate-400 border-b border-slate-100">Audit Status</th>
                  </tr>
                </thead>
                <tbody className="text-[11px] divide-y divide-slate-50">
                  {ledger.length === 0 ? (
                    <tr>
                      <td colSpan={2} className="px-5 py-20 text-center text-slate-300">
                        <LayoutPanelLeft className="w-10 h-10 mx-auto mb-4 opacity-10" />
                        <span className="text-[10px] font-black uppercase tracking-[0.3em] opacity-40">Canvas Initialization Pending</span>
                      </td>
                    </tr>
                  ) : (
                    ledger.map((row) => (
                      <tr key={row.id} className="hover:bg-blue-50/30 transition-all animate-in slide-in-from-right-2">
                        <td className="px-5 py-3">
                          <div className="flex flex-col">
                            <span className="font-bold text-slate-800 truncate">{row.target}</span>
                            <span className="text-[9px] text-slate-400 uppercase">{row.check}</span>
                          </div>
                        </td>
                        <td className="px-5 py-3">
                          <span className={`inline-flex items-center gap-1.5 px-2 py-1 rounded-full text-[9px] font-black uppercase tracking-tighter ${
                            row.status === 'OK' ? 'bg-emerald-100 text-emerald-700 border border-emerald-200' : 'bg-red-100 text-red-700'
                          }`}>
                            {row.status === 'OK' ? <CheckCircle2 className="w-3 h-3" /> : <AlertCircle className="w-3 h-3" />}
                            {row.status}
                          </span>
                        </td>
                      </tr>
                    ))
                  )}
                </tbody>
              </table>
            </div>
          </div>

          {/* Real-time Event Log */}
          <div className="h-44 bg-slate-900 rounded-2xl p-4 flex flex-col border border-slate-800 shadow-2xl">
            <div className="flex items-center justify-between mb-3">
              <span className="text-[9px] font-black text-slate-500 uppercase tracking-widest">System Events</span>
              <div className="w-2 h-2 rounded-full bg-blue-500 animate-pulse" />
            </div>
            <div className="flex-1 overflow-y-auto space-y-2 custom-scrollbar flex flex-col-reverse">
              {kernelLogs.slice(0, 10).map((log, idx) => (
                <div key={idx} className="flex gap-2 text-[10px] font-mono text-emerald-400/70">
                  <span className="text-slate-600">[{log.time}]</span> {log.msg}
                </div>
              ))}
            </div>
          </div>
        </div>
      </aside>

      <style>{`
        @keyframes progress-indeterminate {
          0% { transform: translateX(-100%); width: 30%; }
          100% { transform: translateX(300%); width: 30%; }
        }
        .animate-progress-indeterminate {
          animation: progress-indeterminate 1.5s infinite linear;
        }
      `}</style>
    </div>
  );
};

export default App;
